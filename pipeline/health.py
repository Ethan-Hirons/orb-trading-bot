def entered_vs_booked(root: Path, recent_days: int = 30) -> Check:
    """Every ENTER line should end up as a row in trade_history.csv."""
    logs = _logs(root)
    rows = _history(root)
    booked = Counter((r["date"], r["symbol"]) for r in rows)
    entered: Counter = Counter()
    for day, p in logs.items():
        for ln in open(p, errors="ignore"):
            m = ENTER_RE.search(ln)
            if m:
                entered[(day, m.group(1))] += 1

    today = date.today()
    cutoff = (today - timedelta(days=recent_days)).isoformat()
    # The newest session is exempt ONLY while it is unfinished - still
    # running, or a log copied mid-session. Once it has logged 'Day done',
    # an unbooked entry on it is exactly the failure worth catching, and
    # exempting the whole day would hide the most recent one.
    newest = max(logs) if logs else ""
    newest_open = bool(newest) and "Day done" not in open(
        logs[newest], errors="ignore").read()

    missing = [k for k in entered if k not in booked
               and not (newest_open and k[0] == newest)]
    recent = sorted(k for k in missing if k[0] >= cutoff)
    old = sorted(k for k in missing if k[0] < cutoff)

    detail = [f"{d} {s}" for d, s in recent]
    if old:
        detail.append(f"(+{len(old)} older, earliest {old[0][0]})")
    if recent:
        return Check("entered_vs_booked", FAIL,
                     f"{len(recent)} trade(s) entered but never booked in the "
                     f"last {recent_days} days ({len(missing)} all-time)",
                     detail)
    if old:
        return Check("entered_vs_booked", WARN,
                     f"{len(old)} historical trade(s) never booked "
                     f"(known: day-end-only writes; run backfill.py)", detail)
    return Check("entered_vs_booked", OK,
                 f"all {sum(entered.values())} entries booked")


def stale_xlsx(root: Path, max_lag_days: int = 3) -> Check:
    """trade_log.xlsx is regenerated by hand, so it silently drifts."""
    rows = _history(root)
    if not rows:
        return Check("stale_xlsx", WARN, "no trade_history.csv to compare")
    newest_trade = max(r["date"] for r in rows)
    detail, worst = [], 0
    found = False
    for rel in ("trade_log.xlsx", "live/trade_log.xlsx"):
        p = root / rel
        if not p.exists():
            continue
        found = True
        mtime = date.fromtimestamp(p.stat().st_mtime).isoformat()
        lag = (date.fromisoformat(newest_trade) - date.fromisoformat(mtime)).days
        worst = max(worst, lag)
        detail.append(f"{rel}: written {mtime}, newest trade {newest_trade}, "
                      f"lag {lag}d")
    if not found:
        return Check("stale_xlsx", OK, "no spreadsheet present")
    if worst > max_lag_days:
        return Check("stale_xlsx", WARN,
                     f"spreadsheet {worst} days behind the CSV "
                     f"(run: python live/make_trade_log.py)", detail)
    return Check("stale_xlsx", OK, "spreadsheet current", detail)


def frozen_equity(root: Path, min_run: int = 6) -> Check:
    """Equity identical across many consecutive polls during market hours.

    On 2026-10-23 this was benign (the account had gone to all cash and the
    heartbeat had dropped to its 5-minute cadence). It is only alarming while
    a position is open - but the log alone cannot always tell, so this
    reports rather than fails."""
    logs = _logs(root)
    if not logs:
        return Check("frozen_equity", WARN, "no logs")
    day = max(logs)
    vals: list[tuple[str, str]] = []
    for ln in open(logs[day], errors="ignore"):
        m = EQUITY_RE.search(ln)
        if m:
            vals.append((f"{m.group(1)}:{m.group(2)}", m.group(3)))
    if not vals:
        return Check("frozen_equity", OK, f"{day}: no equity polls logged")
    best_run, run, start = 1, 1, vals[0][0]
    best_start, best_val = vals[0][0], vals[0][1]
    for i in range(1, len(vals)):
        if vals[i][1] == vals[i - 1][1]:
            run += 1
            if run > best_run:
                best_run, best_start, best_val = run, start, vals[i][1]
        else:
            run, start = 1, vals[i][0]
    if best_run >= min_run:
        return Check("frozen_equity", WARN,
                     f"{day}: equity stuck at {best_val} for {best_run} "
                     f"consecutive polls from {best_start}",
                     ["benign if the account was flat; check for an open "
                      "position or a halted symbol"])
    return Check("frozen_equity", OK,
                 f"{day}: equity moving ({len(vals)} polls, longest flat run "
                 f"{best_run})")


def reanchor_rate(root: Path, recent_days: int = 30) -> Check:
    """How often the bracket is actually re-priced to the fill.

    _reanchor_exits returns early when |fill-ref|/ref < 0.001, so the stop
    keeps its ref-anchored level. Low rates are EXPECTED, not a fault; this
    reports the number so the replay harness can be kept honest."""
    logs = _logs(root)
    cutoff = (date.today() - timedelta(days=recent_days)).isoformat()
    enters = reanchors = 0
    for day, p in logs.items():
        if day < cutoff:
            continue
        for ln in open(p, errors="ignore"):
            if ENTER_RE.search(ln):
                enters += 1
            elif "exits re-anchored" in ln:
                reanchors += 1
    if not enters:
        return Check("reanchor_rate", OK,
                     f"no entries in the last {recent_days} days")
    pct = reanchors / enters * 100
    return Check("reanchor_rate", OK,
                 f"{reanchors}/{enters} entries re-anchored ({pct:.0f}%) "
                 f"in the last {recent_days} days",
                 ["the rest keep a ref-anchored stop; replay.py's "
                  "REANCHOR_DRIFT must match runner.py's threshold"])


TS_RE = re.compile(r"^(\d{4}-\d\d-\d\d) (\d\d):(\d\d):(\d\d)")


def _looks_truncated(path: Path, day: str, tol_min: int = 30) -> bool:
    """True if the file was COPIED mid-session rather than the session dying.

    A log synced down from the VPS while the bot is still running ends
    abruptly with no closing markers - identical in content to a session that
    was killed. The tell is the file's mtime: on a mid-session copy it sits
    right after the last line it contains, because the copy IS what set it.
    On a real kill the bot keeps the file open and mtime lands much later.
    """
    last = None
    try:
        for ln in open(path, errors="ignore"):
            m = TS_RE.match(ln)
            if m:
                last = m
    except OSError:
        return False
    if last is None:
        return False
    try:
        from zoneinfo import ZoneInfo
        tz = ZoneInfo("America/New_York")
    except Exception:
        return False
    stamp = datetime(int(day[:4]), int(day[5:7]), int(day[8:10]),
                     int(last.group(2)), int(last.group(3)),
                     int(last.group(4)), tzinfo=tz)
    gap_min = abs(path.stat().st_mtime - stamp.timestamp()) / 60
    return gap_min <= tol_min


def session_integrity(root: Path) -> Check:
    """A finished session logs both 'Day done' and 'Flatten verified'."""
    logs = _logs(root)
    if not logs:
        return Check("session_integrity", WARN, "no logs")
    day = max(logs)
    path = logs[day]
    text = open(path, errors="ignore").read()
    errors = text.count("[ERROR]")
    done = "Day done" in text
    flat = "Flatten verified" in text
    detail = [f"{day}: Day done={done}  Flatten verified={flat}  "
              f"ERROR lines={errors}"]
    # A session still in progress has neither; only complain after the close.
    if not done and day < date.today().isoformat():
        if _looks_truncated(path, day):
            return Check("session_integrity", WARN,
                         f"{day}: no 'Day done', but this log looks like a "
                         f"mid-session COPY, not a killed session",
                         detail + ["file mtime sits right after its last "
                                   "line - check the source instance"])
        return Check("session_integrity", FAIL,
                     f"{day} ended without 'Day done' - killed mid-session?",
                     detail)
    if errors:
        return Check("session_integrity", WARN,
                     f"{day}: {errors} ERROR line(s)", detail)
    return Check("session_integrity", OK, f"{day}: clean", detail)


def features_header(root: Path) -> Check:
    """trade_features.csv header was written once, at file creation, and
    predates v1.12's extra field. A tolerant parser shifts columns silently."""
    p = root / "state" / "trade_features.csv"
    if not p.exists():
        return Check("features_header", OK, "no trade_features.csv")
    with open(p, newline="", encoding="utf-8", errors="ignore") as fh:
        rows = list(csv.reader(fh))
    if len(rows) < 2:
        return Check("features_header", OK, "no data rows")
    head = len(rows[0])
    widths = Counter(len(r) for r in rows[1:] if r)
    worst = max(widths)
    if worst != head:
        return Check("features_header", FAIL,
                     f"header has {head} fields but data rows have "
                     f"{sorted(widths)} - columns will be misread",
                     [f"{n} row(s) of width {w}" for w, n in
                      sorted(widths.items())])
    return Check("features_header", OK,
                 f"header matches {sum(widths.values())} data rows "
                 f"({head} fields)")


def heartbeat_age(root: Path, max_age_days: int = 4) -> Check:
    p = root / "state" / "watchdog_heartbeat.json"
    if not p.exists():
        return Check("heartbeat_age", WARN,
                     "no state/watchdog_heartbeat.json - watchdog never ran")
    age = (time.time() - p.stat().st_mtime) / 86400
    if age > max_age_days:
        return Check("heartbeat_age", WARN,
                     f"watchdog heartbeat is {age:.1f} days old")
    return Check("heartbeat_age", OK, f"heartbeat {age:.1f} days old")


CHECKS = [entered_vs_booked, stale_xlsx, frozen_equity, reanchor_rate,
          session_integrity, features_header, heartbeat_age]


def run_all(root: Path | None = None) -> list[Check]:
    root = Path(root) if root else REPO
    out = []
    for fn in CHECKS:
        try:
            out.append(fn(root))
        except Exception as e:  # a broken check must never mask the others
            out.append(Check(fn.__name__, WARN, f"check raised: {e!r}"))
    return out


def render(checks: list[Check], root: Path | None = None) -> str:
    mark = {OK: "ok  ", WARN: "WARN", FAIL: "FAIL"}
    root = Path(root) if root else REPO
    lines = [f"ORB ops report  {datetime.now():%Y-%m-%d %H:%M}  {root.name}",
             "=" * 66]
    for c in checks:
        lines.append(f"[{mark[c.status]}] {c.name:20s} {c.summary}")
        for d in c.detail:
            lines.append(f"            {d}")
    n_fail = sum(c.failed for c in checks)
    n_warn = sum(c.status == WARN for c in checks)
    lines += ["=" * 66,
              f"{len(checks)} checks: {n_fail} fail, {n_warn} warn"]
    return "\n".join(lines)


def to_json(checks: list[Check]) -> str:
    return json.dumps([{"name": c.name, "status": c.status,
                        "summary": c.summary, "detail": c.detail}
                       for c in checks], indent=2)
