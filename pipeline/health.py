"""Ops checks: what invariants.py is structurally blind to.

invariants.py validates sessions it can see. These checks look at the seams
BETWEEN artefacts, which is where this project's failures have actually
lived: a session that ran but did not book its trades, a spreadsheet nobody
regenerated, an equity feed that froze while a position was open.

Every check here was written from a real incident:

  entered_vs_booked   8 trades entered and never booked (2026-10-25 finding);
                      cause is day-end-only writes, so any mid-session stop
                      loses them until backfill.py runs
  stale_xlsx          live/trade_log.xlsx was 11 days behind the CSV
  frozen_equity       2026-10-23: equity identical to the cent for 45+ min
                      while two positions were open
  reanchor_rate       _reanchor_exits skips when drift < 0.1%, so most stops
                      sit at a different distance than configured
  session_integrity   08-26/08-27 died mid-day: no Day done, no Flatten
  features_header     trade_features.csv header predates v1.12's extra field,
                      so a tolerant parser silently shifts columns

A check returns ok/warn/fail. Only `fail` sets the exit code: a warning that
cries wolf gets ignored, and this project has already lost sessions to
ignored silence.
"""

from __future__ import annotations

import csv
import json
import re
import time
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from datetime import date, datetime, timedelta
from pathlib import Path

from . import LOGS, REPO, STATE

ENTER_RE = re.compile(r"ENTER (?:LONG|SHORT) (\w+) qty=(\S+) ref=([\d.]+)")
EQUITY_RE = re.compile(r"(\d\d):(\d\d):\d\d[,.]\d+ \[INFO\] Equity ([\d.]+)")
LOG_RE = re.compile(r"orb_(\d{4}-\d{2}-\d{2})\.log$")

OK, WARN, FAIL = "ok", "warn", "fail"


@dataclass
class Check:
    name: str
    status: str
    summary: str
    detail: list[str] = field(default_factory=list)

    @property
    def failed(self) -> bool:
        return self.status == FAIL


def _logs(root: Path) -> dict[str, Path]:
    out = {}
    for p in sorted((root / "logs").glob("orb_*.log")):
        m = LOG_RE.search(p.name)
        if m:
            out[m.group(1)] = p
    return out


def _history(root: Path) -> list[dict]:
    f = root / "state" / "trade_history.csv"
    if not f.exists():
        return []
    with open(f, newline="", encoding="utf-8", errors="ignore") as fh:
        return list(csv.DictReader(fh))


